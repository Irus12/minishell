#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*s2;

	s2 = s;
	while (n > 0)
	{
		*s2 = (unsigned char) c;
		s2++;
		n--;
	}
	return (s);
}
